import { useActionState, useEffect, useId, useRef, useState } from 'react';
import { useFormStatus } from 'react-dom';
import { Search, X } from 'lucide-react';
import { Button } from '@/components/ui/button';
import { Field, Input, Label, PressLabel, Textarea } from '@/components/ui/field';
import { cardVariants } from '@/components/ui/card';
import { cn } from '@/lib/cn';
import { MIN_QUERY, type SearchHit } from '@/lib/search/sources';
import { MAX_QUIZ_NOTES } from '@/lib/learn/quiz/model';
import { QUIZ_FILE_ACCEPT } from '@/lib/learn/quiz/file';
import { startQuiz, type NewQuizState } from './actions';
import { IconButton } from '@/components/ui/icon-button';
import { Tooltip } from '@/components/ui/tooltip';

/**
 * Choosing what to be quizzed on.
 *
 * Notes are found by typing, the same search the command palette runs, and the
 * endpoint narrows it to notes -- so this box cannot offer you an order or a
 * job application to be quizzed on. The debounce, the aborted request and the
 * rows staying put while a newer answer lands are all solved next door in
 * components/todo/link-picker.tsx and solved the same way here.
 *
 * Nothing is generated by this form. It ends with a quiz that has material and
 * no questions, and the questions are written on the screen it lands on.
 */

/** A note that has been picked, in the terms the form submits. */
type PickedNote = { id: string; title: string; subtitle: string | null };

function StartButton({ ready }: { ready: boolean }) {
  const { pending } = useFormStatus();
  return (
    <Button type="submit" disabled={pending || !ready}>
      {pending ? 'Setting it up…' : 'Start the quiz'}
    </Button>
  );
}

function NoteSearch({
  picked,
  onPick,
}: {
  picked: readonly PickedNote[];
  onPick: (note: PickedNote) => void;
}) {
  const [query, setQuery] = useState('');
  const fieldId = useId();
  /**
   * The last answer and the query it answered, kept together so "is something
   * still on its way" is derived rather than stored. It is also what stops a
   * slow answer to an earlier query replacing a newer one.
   */
  const [answer, setAnswer] = useState<{ query: string; hits: SearchHit[] } | null>(null);

  const needle = query.trim();
  const searching = needle.length >= MIN_QUERY;
  const looking = searching && answer?.query !== needle;
  const full = picked.length >= MAX_QUIZ_NOTES;

  useEffect(() => {
    if (!searching) return;

    const controller = new AbortController();
    const timer = setTimeout(() => {
      fetch(`/api/search?q=${encodeURIComponent(needle)}&for=quiz`, { signal: controller.signal })
        .then((response) => (response.ok ? response.json() : { hits: [] }))
        .then((body: { hits?: SearchHit[] }) => setAnswer({ query: needle, hits: body.hits ?? [] }))
        .catch(() => {
          // An aborted request is the normal case rather than a failure -- the
          // next keystroke cancelled it -- and a vault that is down is not this
          // control's news to break. Either way the field still works.
        });
    }, 150);

    return () => {
      clearTimeout(timer);
      controller.abort();
    };
  }, [needle, searching]);

  const hits = (searching ? (answer?.hits ?? []) : []).filter(
    (hit) => !picked.some((note) => note.id === hit.id),
  );

  return (
    <div>
      <div className="relative flex items-center gap-2 border-b border-border">
        <Search className="size-4 shrink-0 text-ink-muted" strokeWidth={1.75} aria-hidden />
        <PressLabel htmlFor={fieldId} />
        <input
          id={fieldId}
          value={query}
          onChange={(event) => setQuery(event.target.value)}
          onKeyDown={(event) => {
            // Never a submit: Enter in a search box means "that one", and the
            // form around it is not finished being filled in.
            if (event.key === 'Enter') event.preventDefault();
          }}
          placeholder="Find a note or folder"
          aria-label="Find a note or folder"
          disabled={full}
          data-focus-ring="none"
          className="relative h-(--control-h) w-full bg-transparent text-ui text-ink outline-none placeholder:text-ink-ghost"
        />
      </div>

      {/* Nothing under the box until there is something to say: the
          placeholder already says what to type. */}
      {full ? (
        <p className="py-2 text-small text-ink-muted">{MAX_QUIZ_NOTES} notes at most.</p>
      ) : !searching ? null : hits.length === 0 ? (
        <p className="py-2 text-small text-ink-muted">
          {looking ? 'Looking…' : `No note matches “${needle}”.`}
        </p>
      ) : (
        <ul className="max-h-56 divide-y divide-border overflow-y-auto">
          {hits.map((hit) => (
            <li key={hit.id}>
              <button
                type="button"
                onClick={() => onPick({ id: hit.id, title: hit.title, subtitle: hit.subtitle })}
                className="press flex w-full items-center gap-2.5 rounded-control px-1 py-1.5 text-left transition-colors hover:bg-sunken"
              >
                <span className="min-w-0 flex-1 truncate text-ui text-ink">{hit.title}</span>
                {hit.subtitle && (
                  <span className="shrink-0 text-small text-ink-muted">{hit.subtitle}</span>
                )}
              </button>
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}

export function QuizForm({ maxPasteChars }: { maxPasteChars: number }) {
  const [state, formAction] = useActionState<NewQuizState, FormData>(startQuiz, {});
  const [picked, setPicked] = useState<PickedNote[]>([]);
  const [pasting, setPasting] = useState(false);
  const [paste, setPaste] = useState('');
  const [file, setFile] = useState<string | null>(null);
  const fileRef = useRef<HTMLInputElement>(null);

  const ready = picked.length > 0 || paste.trim().length > 0 || file !== null;

  return (
    <form action={formAction} className={cn(cardVariants({ padding: 'standard' }))}>
      {/* The answer travels with the form rather than through a second piece
          of state at the caller: what was picked is submitted with the rest or
          not at all. */}
      {picked.map((note) => (
        <input key={note.id} type="hidden" name="noteId" value={note.id} />
      ))}

      <Field label="Notes" id="quiz-notes">
        <div id="quiz-notes">
          {picked.length > 0 && (
            <ul className="mb-2 flex flex-wrap gap-1.5">
              {picked.map((note) => (
                <li
                  key={note.id}
                  className="inline-flex max-w-xs items-center gap-1.5 rounded-pill bg-sunken py-1 pl-2.5 pr-1 text-small text-ink"
                >
                  <span className="min-w-0 truncate">{note.title}</span>
                  <Tooltip label="Take this note out of the quiz" className="shrink-0">
                    <IconButton
                      size="sm"
                      label={`Take ${note.title} out of this quiz`}
                      onClick={() => setPicked((all) => all.filter((one) => one.id !== note.id))}
                    >
                      <X strokeWidth={1.75} aria-hidden />
                    </IconButton>
                  </Tooltip>
                </li>
              ))}
            </ul>
          )}

          <NoteSearch
            picked={picked}
            onPick={(note) => setPicked((all) => (all.some((one) => one.id === note.id) ? all : [...all, note]))}
          />
        </div>
      </Field>

      {/* Text or a file, as two buttons on one row. The native file control is
          hidden and pressed through ours, so both read as the same kind of
          thing, and the paste box opens only when it is asked for. */}
      <div className="mt-4" role="group" aria-labelledby="quiz-add-label">
        <Label id="quiz-add-label">Or add</Label>
        <input
          ref={fileRef}
          id="quiz-file"
          name="file"
          type="file"
          accept={QUIZ_FILE_ACCEPT}
          onChange={(event) => setFile(event.target.files?.[0]?.name ?? null)}
          className="hidden"
        />
        <div className="flex flex-wrap items-center gap-2">
          {file ? (
            <span className="inline-flex max-w-full items-center gap-1.5 rounded-pill bg-sunken py-1 pl-2.5 pr-1 text-small text-ink">
              <span className="min-w-0 truncate">{file}</span>
              <Tooltip label="Take this file out of the quiz" className="shrink-0">
                <IconButton
                  size="sm"
                  label={`Take ${file} out of this quiz`}
                  onClick={() => {
                    if (fileRef.current) fileRef.current.value = '';
                    setFile(null);
                  }}
                >
                  <X strokeWidth={1.75} aria-hidden />
                </IconButton>
              </Tooltip>
            </span>
          ) : (
            <Button type="button" variant="secondary" onClick={() => fileRef.current?.click()}>
              Choose file
            </Button>
          )}
          {!pasting && (
            <Button type="button" variant="secondary" onClick={() => setPasting(true)}>
              Paste text
            </Button>
          )}
          {!file && <span className="text-small text-ink-muted">.txt or .md</span>}
        </div>

        {pasting && (
          <Textarea
            id="quiz-paste"
            name="paste"
            aria-label="Text to be quizzed on"
            rows={5}
            autoFocus
            maxLength={maxPasteChars}
            value={paste}
            onChange={(event) => setPaste(event.target.value)}
            placeholder="A job description, a spec, a chapter"
            className="mt-2"
          />
        )}
      </div>

      <Field label="Preparing for" id="quiz-preparing-for" className="mt-4">
        <Input
          id="quiz-preparing-for"
          name="preparingFor"
          maxLength={200}
          placeholder="An interview on Thursday (optional)"
        />
      </Field>

      <div className="mt-4 flex flex-wrap items-center gap-3">
        <StartButton ready={ready} />
        {state.error ? (
          <span className="text-ui text-danger">{state.error}</span>
        ) : (
          !ready && <span className="text-small text-ink-muted">Add a note, text or a file first.</span>
        )}
      </div>
    </form>
  );
}

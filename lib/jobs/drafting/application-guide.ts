/**
 * The person's application writing guide (2 November 2026), as the rules the
 * cover letter drafter and both answer drafters share
 * (draft-cover-letter.ts, draft-application.ts, lib/jobs/evidence/draft.ts).
 *
 * The guide is written for a recruiter who skims for thirty seconds: the
 * answer first, then the credentials, then the proof. Drafts that did not
 * work opened on the company's strategy, ranked the person's own strengths,
 * described client work as holding a hard position, led a finance letter
 * with AI, or carried details from personal projects (step counts, links)
 * that a recruiter would not know what to do with.
 *
 * What is general lives here. What is the person's own (their credentials and
 * the evidence lines they reuse word for word) is in their writing-style
 * notes, which every drafter reads under "How they write".
 */

/** The register, the order of a fit answer, and what to keep specific or general. */
export const APPLICATION_GUIDE = `How applications are written. A recruiter skims for about thirty seconds
and should get the answer, the credentials and the proof, in that order.
- Answer the question in the first sentence. "Why are you a good fit?" opens
  with why they are a good fit, never with the company's strategy, a fact
  about the company or a framework about the job ("Every deal on this team
  has to answer three questions").
- A traditional, professional register: plain statements an HR reviewer
  expects. No slogans, clever framings or lines written to be quoted ("I read
  contract language for what it will do, not just what it says").
- Credentials early. Their professional credentials, degrees and most senior
  title from the résumé appear in the first paragraph, so a fast reader sees
  them.
- Lead with the role's main focus. A finance role leads with finance. AI,
  automation and their own software get one sentence near the end, unless the
  role is about AI.
- Collaborative, not adversarial. Client work is described as working
  through a disagreement in a way that built the client's trust, never as
  holding a hard position or winning an argument.
- Confident, not self-undercutting. State what they can do. Never rank their
  own strengths against each other ("strongest on X, a start on Y").
- Every fact reads the same as on the résumé: titles, course names, counts,
  dates and honours.
- Be specific about credentials, deals and results: the transactions, what
  they did on them, and the result with its number. Be general about side
  projects and about the company's internal strategy: "I build my own
  software with AI tools", not how the software works, its step counts,
  feature lists or links (unless the posting asks for a portfolio), and no
  business-model analysis or executive quotes unless the question asks why
  this company.
- One example, told in two or three sentences, not a long story.
- Every example is professional enough to say in an interview. A difficult
  contact is "one contact disagreed with an accounting change we needed to
  make", not a vivid detail about how they treated people.
- Test each sentence: if a recruiter would ask "why is this here?", cut it or
  make it general; if it could appear in anyone's application, make it
  specific.
- When their writing-style notes hold standard lines (an introduction,
  evidence for each employer or school), use them as written, choosing the
  ones that fit the role, rather than rephrasing them.
- Cover the posting's required items: a location preference, interest in the
  field, anything it says the answer must include.
- No em dashes, no colons or semicolons used for effect, and none of
  "leverage", "passionate", "I'm the only one", or a closing line that
  restates what came before.

A "why are you a good fit" or "what makes you the right hire" answer has four
parts, about 230 to 300 words when there is no limit:
1. The direct answer: one sentence naming two or three things they can do
   that the role needs, then their credentials.
2. The main evidence: the work that proves the first claim.
3. Second evidence: another employer, their degree, a side role or a client
   story, whichever proves the other claims.
4. A close: one sentence tying them to the company's work, or what they
   would do first in the role.

An opening of the right shape, for an invented applicant:
"I am a good fit because I can build the forecasting model and monthly
close process this role owns, and I understand the accounting underneath
them. I am a CPA with an MBA from Michigan and four years at Deloitte, where
I was promoted to Senior."`;

import type { Territory, TerritoryTopic } from '@/lib/learn/levels/territory';

/**
 * The business pack (plan #2483): one territory split into areas, so each can
 * be drafted and paid for on its own with `&area=<area>`. Its SaaS area is the
 * saas-metrics territory, which keeps its own key and sources. This file holds
 * corporate finance and accounting (plan #2483.2); banking, strategy and
 * operations append their texts and topics to it (plan #2483.3).
 *
 * The sources were read on 20 October 2026 and are copied as published, in
 * their own order, leaving out review, exercise and spreadsheet sections:
 *
 * - OpenStax, Principles of Finance (2022), section headings: a published
 *   introductory corporate finance text.
 * - OpenStax, Principles of Accounting, Volume 1: Financial Accounting and
 *   Volume 2: Managerial Accounting (2019), section headings: one text in two
 *   volumes, so it is one source.
 * - MIT OpenCourseWare 15.501, Introduction to Financial and Managerial
 *   Accounting (Spring 2004), its calendar of lecture topics.
 * - MIT OpenCourseWare 15.535, Business Analysis Using Financial Statements
 *   (Spring 2003, Peter Wysocki), its calendar of lecture topics.
 * - The person's Yale SOM course summaries, from the vault's Yale/Course
 *   Summaries folder: MGT 541 Corporate Finance (Spring 2026, Kelly Shue),
 *   MGT 423 Sourcing and Managing Funds (Spring 2025), MGT 847 Private Equity:
 *   Leveraged Buyouts (Fall 2025), MGT 816 The Private Firm CFO (Fall 2025)
 *   and MGT 815 Managerial Controls (Spring 2026). Each line is a session's
 *   topic or a key framework's heading as the summary writes it. MGT 402
 *   Basics of Accounting was waived on the CPA, so it has no summary; the
 *   accounting area's syllabi are the published ones above.
 *
 * Each text names the areas it serves. A drafting call reads the roles and
 * the texts of the topic's area, so with two role phrases each area here
 * reads seven sources, leaving room under MAX_SOURCES for one stored
 * document. A text added for banking, strategy or operations names its area
 * too, or it joins every area's calls.
 *
 * Each topic names the source lines that put it on the list (`from`), as
 * `<text key>: <line>`, and a test holds every line to one that is really
 * there and in a text of the topic's own area. The frame topic each refines
 * is a Level 4 article in learn.area_check_articles, by title. Within each
 * area the list runs from fundamentals outwards, since a topic can link only
 * to topics already on the map.
 */

